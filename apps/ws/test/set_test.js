// 결정 102: 테스트판 문구 · 아래 뒤로 버튼(위 < 없음) · 알림 줄 세우기 · 소장 환경설정
const { chromium } = require('playwright');
const fs = require('fs');
const QRLIB = fs.readFileSync(require.resolve('qrcodejs2/qrcode.min.js'), 'utf8');
const GU = 'https://n-test-0lu-script.googleusercontent.com';
const fmFile = require('./fm_serve.js');
(async () => {
  await fetch('http://localhost:8123/seed');
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  await c.route('https://fonts.googleapis.com/**', r => r.fulfill({ contentType: 'text/css', body: '' }));
  await c.route('https://cdnjs.cloudflare.com/**', r => r.fulfill({ contentType: 'application/javascript', body: QRLIB }));
  await c.route('https://avenuel-fm.github.io/fm/**', r => { const o = fmFile(new URL(r.request().url()).pathname.replace(/^\/fm\//, ''), GU + '/macros/s/TEST/exec', true);
    r.fulfill({ status: 200, contentType: o.type, body: o.body }); });
  await c.route(GU + '/**', async r => { const u = new URL(r.request().url());
    const target = u.pathname.startsWith('/macros/') ? '/index?exec=' + encodeURIComponent('https://avenuel-fm.github.io/fm/ws/') : u.pathname + u.search;
    r.fulfill({ response: await r.fetch({ url: 'http://localhost:8123' + target }) }); });
  const p = await c.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
  p.on('dialog', d => d.accept());
  const fr = () => p.frameLocator('iframe');
  const inner = () => p.frames().find(f => f.url().startsWith(GU));
  const ok = (cond, msg) => console.log((cond ? '' : 'FAIL ') + msg);
  await p.goto('https://avenuel-fm.github.io/fm/ws/');
  await fr().locator('.key').first().waitFor();
  for (const k of '1234') await fr().locator(`.key:text-is("${k}")`).click();
  await fr().locator('.grid6').waitFor();
  const ban = await fr().locator('.banner').first().innerText();
  ok(/^이 버전은 테스트판 입니다\. v\d+\.\d+\.\d+$/.test(ban.trim()), '1) 메인 문구: ' + ban.trim());
  ok(await fr().locator('.backbar').count() === 0, '2) 메인에는 뒤로 버튼 없음');
  // 알림 줄 세우기: 두 개를 넣으면 첫 번째 → (보이는 시간 + 0.5초) → 두 번째
  await inner().evaluate(() => { store('ws_toast_sec', '1'); toast('첫째'); toast('둘째'); });
  const seen = []; const t0 = Date.now();
  while (Date.now() - t0 < 3500) { const t = await inner().evaluate(() => { const e = document.querySelector('.toast'); return e && !e.classList.contains('hide') ? e.textContent : ''; }); if (seen[seen.length - 1] !== t) seen.push(t); await p.waitForTimeout(100); }
  ok(seen.join('|') === '첫째||둘째|', '3) 알림이 하나씩, 사이에 쉼: ' + seen.join(' → '));
  await fr().locator('button:text-is("환경설정")').click();
  await fr().locator('.strow').first().waitFor();
  ok(await fr().locator('.top .back').count() === 0 && await fr().locator('.backbar button').count() === 1, '4) 위 < 없음, 아래 뒤로 버튼');
  ok(await fr().locator('.backbar').evaluate(e => getComputedStyle(e).position === 'sticky' && e.getBoundingClientRect().bottom <= innerHeight + 1), '4-1) 뒤로 줄이 화면 아래에 붙어 늘 보임 (11-13)');
  ok(await fr().locator('.strow:has-text("김철수")').count() === 1, '5) 직원 목록에 김철수');
  await fr().locator('button:text-is("+ 직원 추가")').click();
  await fr().locator('#sfN').fill('박영희'); await fr().locator('#sfP').fill('기건파트'); await fr().locator('#sfX').fill('2468');
  await fr().locator('#sfB').click();
  await fr().locator('.strow:has-text("박영희")').waitFor();
  ok(true, '6) 직원 추가 → 목록에 박영희');
  await fr().locator('.strow:has-text("박영희") button:text-is("편집")').click();
  await fr().locator('#sfR').selectOption('파트장'); await fr().locator('#sfB').click();
  await fr().locator('.strow:has-text("박영희"):has-text("파트장")').waitFor();
  ok(true, '7) 편집 → 파트장');
  await fr().locator('.strow:has-text("박영희") button:text-is("PIN 변경")').click();
  await fr().locator('#spX').fill('1234'); await fr().locator('#spB').click();
  await p.waitForTimeout(400);
  ok(/다른 직원/.test(await fr().locator('#spM').innerText()), '8) 남의 PIN으로는 못 바꿈');
  await fr().locator('#spX').fill('1357'); await fr().locator('#spB').click(); await p.waitForTimeout(400);
  ok(await fr().locator('#spX').count() === 0, '9) PIN 변경');
  await p.screenshot({ path: 'shot_set.png' });
  await fr().locator('.strow:has-text("박영희") button:text-is("삭제")').click();
  await p.waitForTimeout(600);
  ok(await fr().locator('.strow:has-text("박영희")').count() === 0, '10) 삭제 → 목록에서 빠짐');
  ok(await fr().locator('.strow:has-text("홍길동") button:text-is("삭제")').count() === 0, '11) 내 계정은 삭제 버튼 없음');
  await fr().locator('.backbar button').click(); await fr().locator('.grid6').waitFor();
  ok(true, '12) 아래 뒤로 → 메인');
  await fr().locator('.tile:has(b:text-is("서류작업"))').click(); await fr().locator('.backbar').waitFor();
  await p.screenshot({ path: 'shot_backbar.png', fullPage: true });
  ok(errs.length === 0, '13) 화면 오류 없음 ' + errs.join(' / '));
  await b.close();
})().catch(e => { console.log('FAIL ' + e.message); process.exit(1); });
