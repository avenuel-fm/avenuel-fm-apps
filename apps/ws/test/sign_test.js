const { chromium } = require('playwright');
const fs = require('fs');
const QRLIB = fs.readFileSync(require.resolve('qrcodejs2/qrcode.min.js'), 'utf8');
(async () => {
  await fetch('http://localhost:8123/seed');
  const b = await chromium.launch();
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  await c.route('https://cdnjs.cloudflare.com/**', r => r.fulfill({ contentType: 'application/javascript', body: QRLIB }));
  await c.route('https://fonts.googleapis.com/**', r => r.fulfill({ contentType: 'text/css', body: '' }));
  const p = await c.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
  let signLen = 0;
  p.on('request', r => { if (r.url().endsWith('/run')) { const d = r.postData() || ''; const m = /data:image\/png;base64,[A-Za-z0-9+/=]+/.exec(d); if (m) signLen = m[0].length; } });
  const pin = async s => { for (const k of s) await p.click(`.key:text-is("${k}")`); };
  const draw = async (pts) => { const bb = await p.locator('#spad canvas.i').boundingBox(); await p.mouse.move(bb.x + pts[0][0] * bb.width, bb.y + pts[0][1] * bb.height); await p.mouse.down(); for (const q of pts.slice(1)) await p.mouse.move(bb.x + q[0] * bb.width, bb.y + q[1] * bb.height, { steps: 4 }); await p.mouse.up(); };
  await p.goto('http://localhost:8123/index');
  await pin('5678');
  await p.waitForSelector('#spad');
  const t1 = await p.locator('b').filter({ hasText: '서명해 주세요' }).innerText();
  console.log('1) PIN 맞음 → 서명 화면:', t1, '· 버튼 잠김', await p.locator('#sGo').isDisabled(), '· 건너뛰기 없음', await p.locator('button:has-text("건너")').count() === 0);
  await p.screenshot({ path: 'shot_sign_empty.png' });
  await draw([[0.5, 0.5], [0.52, 0.52]]);
  await p.click('#sGo'); await p.waitForTimeout(200);
  console.log('2) 짧은 서명 →', await p.locator('#sMsg').innerText());
  await p.click('#sClr');
  const pts = []; for (let i = 0; i <= 40; i++) pts.push([0.15 + i * 0.017, 0.5 + 0.25 * Math.sin(i / 3)]);
  await draw(pts); await draw([[0.3, 0.3], [0.35, 0.75], [0.6, 0.3], [0.7, 0.7]]);
  await p.screenshot({ path: 'shot_sign_filled.png' });
  await p.click('#sGo');
  await p.waitForSelector('.grid6');
  console.log('3) 서명하고 로그인 → 메인 · 서명 PNG', signLen, '자 (약', Math.round(signLen * 0.75 / 1024), 'KB) · 타일:', (await p.locator('.tile').first().innerText()).replace(/\n/g, ' '));
  await p.screenshot({ path: 'shot_main_docs.png' });
  await p.locator('.tile').first().click(); await p.click('text=TBM');
  await p.waitForSelector('.sgrow');
  const rows = await p.locator('.sgrow').allInnerTexts();
  console.log('4) TBM 서명 목록:', rows.map(r => r.replace(/\n/g, ' ')).join(' | '));
  console.log('   PDF 버튼(양식 전 잠김):', await p.locator('button:has-text("PDF로 저장")').isDisabled());
  await p.screenshot({ path: 'shot_tbm.png', fullPage: true });
  await p.click('button:has-text("로그아웃")'); await p.waitForSelector('.key');
  await pin('5678'); await p.waitForSelector('.grid6');
  console.log('5) 같은 근무일 다시 로그인 → 서명 안 묻고 메인');
  await p.click('button:has-text("로그아웃")'); await p.waitForSelector('.key');
  await pin('9999'); await p.waitForTimeout(400);
  console.log('6) 틀린 PIN →', await p.locator('#pinMsg').innerText());
  await p.reload(); await p.waitForSelector('.key');
  await pin('1234'); await p.waitForSelector('.grid6');
  console.log('7) 이미 서명한 홍길동 → 바로 메인');
  console.log('오류:', errs.length ? errs : '없음'); await b.close();
})().catch(e => { console.error('ERR', e.message); process.exit(1); });
