"""1.0 브라우저 점검: 모의 백엔드로 미리보기를 열어 실제 사용 흐름을 따라갑니다."""
import asyncio, datetime, pathlib
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).resolve().parent
URL = (ROOT / 'preview.html').as_uri()
OUT = ROOT / 'shots'
OUT.mkdir(exist_ok=True)
TODAY = datetime.date.today()
SOON = (TODAY + datetime.timedelta(days=5)).isoformat()

LONG = '\n'.join(f'{i}. 협의 내용 예시 문단입니다. 분전반 2차측 결선, 감지기 이격거리, 방염 선처리 범위 표기를 다음 차수에 다시 확인합니다. 보완 도면은 CAD 파일로 제출합니다.' for i in range(2, 40))


def check(cond, msg):
    if not cond:
        raise AssertionError(msg)
    print('  ✓', msg)


async def main():
    errors = []
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1280, 'height': 900}, accept_downloads=True)
        page = await ctx.new_page()
        page.on('pageerror', lambda e: errors.append('pageerror: ' + str(e)))
        page.on('console', lambda m: errors.append('console: ' + m.text) if m.type == 'error' and 'fonts.g' not in m.text and 'ERR_' not in m.text else None)
        await page.route('**/fonts.googleapis.com/**', lambda r: r.abort())
        await page.route('**/fonts.gstatic.com/**', lambda r: r.abort())
        await page.goto(URL)
        await page.evaluate('localStorage.clear(); sessionStorage.clear()')
        await page.reload()

        print('로그인')
        await page.fill('#pin', '1234'); await page.click('button[type=submit]')
        await page.wait_for_selector('text=도면협의 대시보드')
        check(True, '소장 로그인 → 대시보드 첫 화면')

        print('새 도면협의 입력')
        await page.click('[data-act=new]')
        await page.wait_for_selector('#f-tenant')
        check(await page.locator('[data-act=delround]').count() == 0, '저장 전에는 차수 삭제 버튼 없음')
        await page.fill('#f-reviewDate', '2026-10-10')
        await page.fill('#f-openDate', '2026-11-20')
        await page.fill('#f-tenant', '테스트 브랜드')
        await page.click('[data-choice=storeType][data-value=본매장]')
        await page.fill('#f-location', '3 동측')
        await page.fill('#f-periodStart', '2026-10-15'); await page.fill('#f-periodEnd', '2026-11-15')
        await page.fill('#f-fireCheckDate', '2026-11-18')
        insp = await page.inner_text('#inspect')
        check('공사기간' in insp and '밖입니다' in insp, '날짜 검사: 합동점검일(11-18)이 공사기간 밖 경고')
        await page.fill('#f-periodEnd', '2026-11-22')
        insp = await page.inner_text('#inspect')
        check('오픈 예정일' in insp and '늦습니다' in insp, '날짜 검사: 공사 종료일이 오픈 예정일보다 늦음 경고')
        await page.fill('#f-periodEnd', '2026-11-19')
        check(await page.locator('#inspect .dwarn').count() == 0, '날짜가 맞으면 경고 사라짐')
        await page.fill('#f-openDate', (TODAY + datetime.timedelta(days=60)).isoformat())  # 고정 날짜가 「7일 내 오픈」 집계에 들어가지 않게

        # 전화 하이픈 · 이메일 검사
        await page.fill('#f-ownerCompany', '발주 주식회사'); await page.fill('#f-ownerName', '김담당')
        await page.click('#f-ownerTel'); await page.keyboard.type('01098765432')
        check(await page.input_value('#f-ownerTel') == '010-9876-5432', '전화번호 자동 하이픈 010-9876-5432')
        await page.fill('#f-ownerEmail', 'owner@example')
        await page.click('#f-contractorCompany')
        check(await page.locator('[data-err=ownerEmail]').is_visible(), '이메일 형식 오류 표시')
        await page.fill('#f-ownerEmail', 'owner@example.com')
        check(not await page.locator('[data-err=ownerEmail]').is_visible(), '이메일 고치면 오류 사라짐')
        await page.fill('#f-contractorCompany', '시공 주식회사'); await page.fill('#f-contractorName', '이소장')
        await page.click('#f-contractorTel'); await page.keyboard.type('01012345678')

        for k, v in [('ceiling', '신설'), ('floor', '재사용'), ('wall', '신설'),
                     ('broadcast', '설치'), ('wanbi', '비해당'), ('tempPartition', '설치'), ('shutter', '있음'), ('smokeCurtain', '없음'), ('controller', '있음'), ('preFR', '있음'), ('postFR', '없음'),
                     ('docInsurance', '제출'), ('docCad', '제출'), ('docFR', '제출'), ('docFRPlan', '미제출')]:
            await page.click(f'[data-choice={k}][data-value="{v}"]')
        check('준공 불가' in await page.inner_text('#docWarn'), '방염계획도 미제출 → "미제출 시 준공 불가" 경고')

        print('주방공사 연동')
        await page.click('[data-choice=kitchen][data-value="있음"]')
        await page.click('[data-choice=waterproof][data-value="시공"]'); await page.click('[data-choice=waterTest][data-value="예정"]')
        await page.click('[data-choice=kitchenExt][data-value="있음"]'); await page.click('[data-choice=gasAlarm][data-value="있음"]')
        await page.fill('#f-exhaustCmh', '1200')
        await page.click('[data-choice=kitchen][data-value="없음"]')
        await page.wait_for_selector('[data-group=kitchenExt].na')
        disabled = await page.evaluate("['exhaustCmh','gasGrade'].every(k => document.getElementById('f-' + k).disabled && document.getElementById('f-' + k).value === '해당없음')")
        vals = await page.evaluate("['waterproof','waterTest','kitchenExt','exhaustCmh','gasGrade','gasAlarm'].map(k => window.__DR.review[k])")
        check(disabled and all(v == '해당없음' for v in vals), '주방 없음 → 6개 항목 해당없음 + 비활성화')
        await page.screenshot(path=OUT / 'v1_kitchen_off.png', full_page=False, clip={'x': 0, 'y': 0, 'width': 1280, 'height': 900})
        await page.click('[data-choice=kitchen][data-value="있음"]')
        vals = await page.evaluate("['waterproof','kitchenExt','exhaustCmh'].map(k => window.__DR.review[k])")
        check(all(v == '' for v in vals) and not await page.is_disabled('#f-exhaustCmh'), '주방 있음으로 바꾸면 다시 입력 가능 (해당없음 해제)')
        await page.click('[data-choice=kitchen][data-value="없음"]')

        print('차단기 · 서명 · 저장')
        await page.fill('#f-elecKw', '45')
        await page.click('[data-choice=powerPhase][data-value="삼상 380V"]')
        await page.fill('#f-mainBreakerA', '150')
        await page.check('[data-field=rulesAck]')
        await page.click('#notes')
        await page.keyboard.type('1. 가스배관 관통부 방화구획 확인 #방화구획')
        await page.wait_for_selector('#gpanel .hit')
        await page.keyboard.press('Enter')
        check('(설비공사 지침 6/10, p.30)' in await page.input_value('#notes'), '#방화구획 → 지침 쪽 번호 삽입')
        await page.fill('#notes', await page.input_value('#notes') + '\n' + LONG)
        await page.click('[data-act=sig][data-key=safetySig]')
        c = page.locator('#sigc'); bx = await c.bounding_box()
        await page.mouse.move(bx['x'] + 60, bx['y'] + 180); await page.mouse.down()
        for i in range(25):
            await page.mouse.move(bx['x'] + 60 + i * 12, bx['y'] + 180 - (40 if i % 2 else 0))
        await page.mouse.up(); await page.click('#sigOk')
        check(await page.locator('[data-key=safetySig] .sigdate').count() == 1, '서명 후 서명 일자 표시')
        await page.click('.tb-actions [data-act=save]')
        await page.wait_for_selector('#hdrDoc:text-matches("에비뉴엘컨펌_001_261010")')
        check(await page.is_disabled('[data-act=delround]'), '1차만 있으면 차수 삭제 버튼 비활성화')

        print('누락 항목 안내 (검토 완료)')
        await page.click('.foot-actions [data-act=finalize]')
        await page.wait_for_selector('#missTitle')
        items = await page.locator('.misslist button').all_inner_texts()
        print('    누락:', ', '.join(items))
        check('영업팀 서명' in items and '공사 책임자 서명' in items, '빠진 서명이 목록에 나옴')
        await page.screenshot(path=OUT / 'v1_missing.png')
        await page.click('.misslist button:text("영업팀 성명")')
        await page.wait_for_timeout(500)
        check(await page.evaluate("document.activeElement && document.activeElement.id") == 'f-salesName', '목록 항목을 누르면 해당 칸으로 이동')
        await page.click('.foot-actions [data-act=finalize]')
        await page.click('#missGo')
        await page.wait_for_selector('.chip.blue:text("검토완료")')
        check(True, '누락 항목이 있어도 "그대로 검토 완료" 저장')

        print('출력 (누락 있어도 출력 가능)')
        await page.click('.tb-actions [data-act=print]')
        await page.wait_for_selector('#pages .page')
        await page.wait_for_timeout(300)
        p1 = page.locator('#pages .page').nth(0)
        t1 = await p1.inner_text()
        check('3층 동측' in t1, '공사위치 "3 동측" → 출력 "3층 동측"')
        check(await p1.locator('.stamp').count() == 0, '컨펌 전 출력물에 "작성중" 표시 없음')
        check('—' in t1, '빈칸은 "—"로 표시')
        check('미제출 시 준공 불가' in t1, '출력물 제출서류 줄에 준공 불가 표시')
        check('해당없음' in t1, '주방 없음 항목이 출력물에 해당없음')
        check(await p1.locator('.psigd').count() == 1, '출력물 서명 칸에 서명 일자')
        overflow = await page.evaluate("(()=>{const p=document.querySelector('#pages .page');return p.scrollHeight - p.clientHeight})()")
        n_pages = await page.locator('#pages .page').count()
        check(overflow <= 0 and n_pages >= 2, f'1쪽 넘침 없음, 별지 포함 {n_pages}쪽')
        await p1.screenshot(path=OUT / 'v1_print_p1.png')
        async with page.expect_download(timeout=60000) as dl:
            await page.click('[data-act=savePdf]')
        d = await dl.value
        await d.save_as(OUT / 'v1_sample.pdf')
        check((OUT / 'v1_sample.pdf').stat().st_size > 200000, 'PDF 저장 ' + d.suggested_filename)

        print('2차 · 변경 표시 · 차수 삭제')
        await page.click('[data-act=backEdit]')
        await page.click('[data-act=next]'); await page.click('.dialog .main-act')
        await page.wait_for_selector('#hdrTitle:text("2차 검토")')
        check('1차 대비 변경 0개' in await page.inner_text('#nav'), '2차 생성 직후 변경 0개')
        await page.fill('#f-elecKw', '60')
        await page.fill('#f-supplyPipeA', '40')
        check(await page.locator('[data-chg=elecKw]').is_visible(), '바뀐 항목(전기용량)에 "변경" 표시')
        check('chg' in (await page.get_attribute('#f-supplyPipeA', 'class')) or await page.locator('[data-chg=supplyPipeA]').is_visible(), '배관 size 변경 표시')
        check('변경 2개' in await page.inner_text('#nav'), '진행 표시에 "1차 대비 변경 2개"')
        await page.screenshot(path=OUT / 'v1_changes.png')
        await page.click('.tb-actions [data-act=save]')
        await page.wait_for_selector('.savestate.ok')
        check(not await page.is_disabled('[data-act=delround]'), '2차가 있으면 삭제 버튼 활성화')
        await page.click('[data-act=delround]')
        await page.wait_for_selector('.dialog')
        dtext = await page.inner_text('.dialog')
        check('2차' in dtext and '에비뉴엘컨펌_001_261010' in dtext and '삭제보관' in dtext, '삭제 확인 팝업: 차수·문서번호·보관 안내')
        await page.screenshot(path=OUT / 'v1_delete_confirm.png')
        await page.click('.dialog .main-act')
        await page.wait_for_selector('#hdrTitle:text("1차 검토")')
        check(await page.is_disabled('[data-act=delround]'), '삭제 후 1차만 남아 버튼 비활성화')

        print('업체 자동완성')
        await page.click('[data-act=dash]')
        await page.wait_for_selector('.tbl')
        await page.click('[data-act=new]')
        await page.wait_for_selector('#f-tenant')
        await page.fill('#f-tenant', '오픈임박 매장'); await page.fill('#f-openDate', SOON); await page.fill('#f-periodEnd', (TODAY + datetime.timedelta(days=3)).isoformat()); await page.click('#fireSug button')
        await page.fill('#f-ownerCompany', '발주 주식회사'); await page.dispatch_event('#f-ownerCompany', 'change')
        check(await page.input_value('#f-ownerName') == '김담당' and await page.input_value('#f-ownerTel') == '010-9876-5432', '업체명 고르면 이전 담당자·연락처 자동 입력')
        await page.click('.tb-actions [data-act=save]')
        await page.wait_for_selector('#hdrDoc:text-matches("에비뉴엘컨펌_002_")')

        print('대시보드 D-day · 컨펌')
        await page.click('[data-act=dash]')
        await page.wait_for_selector('.tbl')
        body = await page.inner_text('#dashBody')
        check('D-5' in body and '합동점검 D-3' in body, '오픈 D-5 · 합동점검 D-3 표시')
        check((await page.inner_text('.kpi.soon .n')) == '1', 'KPI "7일 내 오픈" 1')
        await page.screenshot(path=OUT / 'v1_dashboard.png')
        row = page.locator('tr', has_text='테스트 브랜드')
        await row.locator('[data-act=confirm]').click(); await page.click('.dialog .main-act')
        await page.wait_for_selector('.cf.on')
        await row.locator('[data-act=printFromDash]').click()
        await page.wait_for_selector('#pages .page .stamp.ok')
        check('컨펌완료' in await page.inner_text('#pages .stamp'), '컨펌완료 후 출력물에 컨펌완료 도장')
        await page.locator('#pages .page').nth(0).screenshot(path=OUT / 'v1_print_confirmed.png')
        await page.click('[data-act=backEdit]')
        check(await page.is_disabled('[data-act=delround]'), '컨펌완료 매장은 삭제 버튼 비활성화')

        print('화면 폭')
        for w, h, name in [(834, 1194, 'tablet'), (390, 844, 'phone')]:
            await page.set_viewport_size({'width': w, 'height': h})
            await page.wait_for_timeout(200)
            hs = await page.evaluate('document.documentElement.scrollWidth - document.documentElement.clientWidth')
            check(hs <= 0, f'{name} 가로 넘침 없음')
        await b.close()
    print('ERRORS:', errors if errors else 'none')
    if errors:
        raise SystemExit(1)

asyncio.run(main())
