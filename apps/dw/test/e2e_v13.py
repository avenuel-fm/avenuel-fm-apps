"""1.3 브라우저 점검: 문구 분류·관리 · 끊김 임시 보관 · 적용 지침 · QR · 비슷한 말 · 지침 이전 판"""
import asyncio, pathlib, subprocess, sys, time, json
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / 'shots'
PORT = 8766
URL = f'http://127.0.0.1:{PORT}/preview.html'


def check(cond, msg):
    if not cond:
        raise AssertionError(msg)
    print('  ✓', msg)


async def login(page, url=URL, clear=True):
    await page.goto(url)
    if clear:
        await page.evaluate('localStorage.clear(); sessionStorage.clear()')
        await page.reload()
    await page.fill('#pin', '1234'); await page.click('button[type=submit]')


async def main():
    errors = []
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900})
        page = await ctx.new_page()
        page.on('pageerror', lambda e: errors.append('pageerror: ' + str(e)))
        await page.route('**/fonts.g*/**', lambda r: r.abort())
        await login(page)
        await page.wait_for_selector('[data-act=new]')

        print('자주 쓰는 문구 · 분류')
        await page.click('[data-act=new]')
        await page.wait_for_selector('#notes')
        await page.fill('#f-tenant', '문구 시험')
        await page.click('[data-act=phrases]')
        await page.wait_for_selector('.phmenu')
        cats = await page.locator('[data-phcat]').all_inner_texts()
        check(cats[0] == '전체' and '소방' in cats and '방염' in cats, '분류 버튼: ' + ' '.join(cats))
        await page.click('[data-phcat="소방"]')
        check(await page.locator('#phItems [data-ph]').count() == 2, '소방 분류만 보기 (2개)')
        check(await page.locator('[data-phact=fromsel]').is_disabled(), '특이사항이 비어 있으면 "선택한 문장 저장" 비활성')
        await page.click('#phItems [data-ph] >> nth=0')
        v = await page.input_value('#notes')
        check('감지기는 벽 또는 보에서 0.6m' in v, '소방 문구 삽입')
        # 선택한 문장 → 문구로 저장
        await page.click('#notes'); await page.keyboard.press('Control+End'); await page.keyboard.press('Enter')
        await page.keyboard.type('분전반 차단기 용량 재검토 후 도면 재제출할 것')
        await page.click('[data-act=phrases]')
        await page.click('[data-phact=fromsel]')
        await page.wait_for_selector('#phT')
        check(await page.input_value('#phT') == '분전반 차단기 용량 재검토 후 도면 재제출할 것', '커서가 있는 줄을 문구로 가져옴')
        check(await page.input_value('#phC') == '전기', '분류 자동 추천: 전기')
        await page.click('.dialog .main-act')
        await page.wait_for_function("window.__DR.boot.phrases.length === 6")
        check(True, '문구 저장 (6개)')
        # 문구 관리
        await page.click('[data-act=phrases]'); await page.click('[data-phact=manage]')
        await page.wait_for_selector('.phmgr')
        check(await page.locator('.phrow').count() == 6, '문구 관리: 6줄')
        await page.click('.phrow >> nth=0 >> [data-pm=down]')
        await page.click('.phrow >> nth=5 >> [data-pm=del]')
        await page.click('#phAdd')
        await page.locator('.phrow >> nth=5 >> [data-pk=t]').fill('새로 추가한 설비 문구')
        await page.locator('.phrow >> nth=5 >> [data-pk=c]').select_option('설비')
        await page.screenshot(path=OUT / 'v13_phrase_manager.png')
        await page.click('#phSave')
        await page.wait_for_selector('.phmgr', state='detached')
        ph = await page.evaluate('window.__DR.boot.phrases')
        check(len(ph) == 6 and ph[1]['c'] == '방염' and ph[0]['c'] == '안전' and ph[5] == {'t': '새로 추가한 설비 문구', 'c': '설비'}, '순서 바꾸기·삭제·추가 저장')
        await page.click('[data-act=phrases]')
        await page.screenshot(path=OUT / 'v13_phrase_menu.png')
        await page.keyboard.press('Escape'); await page.click('.overlay', position={'x': 5, 'y': 5})

        print('비슷한 말 검색')
        await page.keyboard.press('Control+k')
        await page.fill('#gq', 'SP')
        await page.wait_for_selector('#gres .hit')
        syn = await page.inner_text('#gres .synline')
        check('스프링클러' in syn and '헤드' in syn, '"SP" 검색 → ' + syn)
        snips = await page.locator('#gres .hit').all_inner_texts()
        check(any('스프링클러' in t for t in snips), '스프링클러가 들어간 결과도 나옴 (' + str(len(snips)) + '건)')
        await page.fill('#gq', '방화구획')
        await page.wait_for_selector('#gres [data-gins]')
        await page.click('#gres [data-gins] >> nth=0')

        print('끊김 대비 임시 보관 (새 매장)')
        await page.evaluate('window.__mockOffline = true')
        await page.click('[data-act=save]')
        await page.wait_for_function("/저장 대기/.test(document.querySelector('#savestate').textContent)")
        pend = await page.evaluate("JSON.parse(localStorage.getItem('dr_pending'))")
        check(len(pend) == 1, '저장 실패 → 이 기기에 보관 1건')
        await page.fill('#f-location', '3')
        await page.click('[data-act=save]')
        await page.wait_for_timeout(400)
        pend = await page.evaluate("JSON.parse(localStorage.getItem('dr_pending'))")
        check(len(pend) == 1 and list(pend.values())[0]['review']['location'] == '3', '다시 저장해도 같은 건을 최신 내용으로 덮어씀')
        await page.click('[data-act=dash]')
        await page.wait_for_selector('#pendingBar')
        await page.wait_for_selector('.pendbar')
        check('임시 보관된 검토서 1건' in await page.inner_text('.pendbar'), '대시보드에 보관 알림')
        await page.screenshot(path=OUT / 'v13_pending.png')
        await page.evaluate('window.__mockOffline = false')
        await page.click('[data-act=pendFlush]')
        await page.wait_for_function("!document.querySelector('.pendbar')", timeout=10000)
        await page.wait_for_function("document.body.innerText.includes('문구 시험')", timeout=10000)
        stores = await page.evaluate("JSON.parse(localStorage.getItem('dr_mockdb')).stores.filter(s => s.tenant === '문구 시험')")
        check(len(stores) == 1 and stores[0]['id'].startswith('c-'), '다시 연결되면 저장 · 매장 1개만 생성')
        sid = stores[0]['id']

        print('적용 지침 · QR')
        await page.goto(URL + '?store=' + sid)
        await page.wait_for_selector('#notes', timeout=10000)
        check(await page.input_value('#f-tenant') == '문구 시험', 'QR 주소(?store=)로 열면 그 매장 검토서가 바로 열림')
        await page.click('[data-act=save]')
        await page.wait_for_function("/저장됨/.test(document.querySelector('#savestate').textContent)")
        gv = await page.evaluate('window.__DR.review.guideVer')
        check(gv == '롯데백화점 Tenant 시설공사 지침 (2024.07.09)', '적용 지침 = 특이사항에 넣은 지침만: ' + gv)
        await page.click('[data-act=print]')
        await page.wait_for_selector('.page .pver')
        pv = await page.inner_text('.page .pver')
        check('적용 지침' in pv and '시설공사 지침' in pv, '출력물에 ' + pv)
        await page.wait_for_function("(() => { const i = document.querySelector('.pqr img'); return i && i.complete && i.naturalWidth > 0; })()")
        check(True, '출력물에 QR 코드')
        await page.wait_for_timeout(300)
        await page.locator('.page >> nth=0').screenshot(path=OUT / 'v13_print.png')
        await page.click('[data-act=backEdit]')

        print('끊김 대비 (기존 매장 수정 후 다시 열기)')
        await page.wait_for_selector('#notes')
        await page.evaluate('window.__mockOffline = true')
        await page.fill('#f-location', '5')
        await page.click('[data-act=save]')
        await page.wait_for_function("/저장 대기/.test(document.querySelector('#savestate').textContent)")
        await page.evaluate('window.__mockOffline = false')
        await page.goto(URL + '?store=' + sid)
        await page.wait_for_selector('#notes', timeout=10000)
        await page.wait_for_timeout(800)
        db = await page.evaluate("JSON.parse(localStorage.getItem('dr_mockdb')).reviews.filter(r => r.storeId === '%s')[0].location" % sid)
        check(db == '5' and await page.input_value('#f-location') == '5', '새로 연 뒤 자동으로 다시 보내 저장됨')

        print('지침 이전 판')
        await page.evaluate("""window.__mockGuides.pdfs.push({ fileId: 'pdf-s27', name: '통합안전관리지침_27(개정).pdf', path: 'guides/통합안전관리지침_26.pdf', size: 15154925, updated: '2026-10-28T15:00:00' })""")
        await page.click('[data-act=dash]')
        await page.wait_for_selector('[data-act=gadmin]')
        await page.click('[data-act=gadmin]')
        await page.wait_for_selector('.gadm')
        prow = page.locator('.gadm .grow').filter(has_text='통합안전관리지침_27(개정).pdf')
        await prow.locator('[data-act=gbuild]').click()
        await page.wait_for_selector('#gfRep')
        await page.fill('#gfTitle', '통합안전관리지침 (27년 개정판)')
        await page.fill('#gfShort', '통합안전관리지침')
        await page.select_option('#gfRep', 's')
        await page.click('.dialog .main-act')
        await page.wait_for_selector('#gbProg')
        await page.wait_for_function("!document.querySelector('#gbProg')", timeout=400000)
        txt = await page.inner_text('.gadm')
        check('이전 판' in txt and '까지 사용' in txt and '통합안전관리지침 (27년 개정판)' in txt, '개정판 색인 완료 · 이전 판 보관')
        await page.screenshot(path=OUT / 'v13_archive.png', full_page=True)
        await page.click('[data-act=dash]')
        await page.click('[data-act=new]')
        await page.wait_for_selector('#notes')
        await page.click('#notes'); await page.keyboard.press('Control+k')
        await page.fill('#gq', '방화구획')
        await page.wait_for_selector('#gres .hit')
        n1 = await page.locator('#gres .hit').count()
        check(await page.locator('[data-gold]').count() == 1, '"이전 판 포함" 버튼 표시')
        await page.click('[data-gold]')
        await page.wait_for_timeout(200)
        n2 = await page.locator('#gres .hit').count()
        tags = await page.locator('#gres .srctag.old').count()
        check(n2 > n1 and tags >= 1, f'이전 판 포함하면 결과 {n1} → {n2}건, 이전 판 표시')
        await page.screenshot(path=OUT / 'v13_search_old.png')
        await b.close()
    print('ERRORS:', errors if errors else 'none')
    if errors:
        raise SystemExit(1)


srv = subprocess.Popen([sys.executable, '-m', 'http.server', str(PORT), '--bind', '127.0.0.1'], cwd=ROOT,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
try:
    time.sleep(1)
    asyncio.run(main())
finally:
    srv.terminate()
