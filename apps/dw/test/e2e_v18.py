"""1.8 브라우저 점검: 시설 소장 확인 · 빠진 항목 · 화재예방단자함 · 설비 교체 · 할 일 · 업체 이력 · 서류 요청 · 변경 요약 · 원격 서명 · PDF 보관 · 발송 기록"""
import asyncio, pathlib, subprocess, sys, time
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / 'shots'
OUT.mkdir(exist_ok=True)
PORT = 8794
URL = f'http://127.0.0.1:{PORT}/preview.html'


def check(cond, msg):
    if not cond:
        raise AssertionError(msg)
    print('  ✓', msg)


async def main():
    errors = []
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1280, 'height': 900})
        page = await ctx.new_page()
        page.on('pageerror', lambda e: errors.append('pageerror: ' + str(e)))
        await page.route('**/fonts.g*/**', lambda r: r.abort())
        ev = page.evaluate
        await page.goto(URL)
        await ev('localStorage.clear(); sessionStorage.clear()'); await page.reload()
        await page.fill('#pin', '1234'); await page.click('#loginForm button[type=submit]')
        await page.wait_for_selector('[data-act=new]')

        print('입력 항목')
        await page.click('[data-act=new]'); await page.wait_for_selector('#notes')
        nav = await page.inner_text('#nav')
        check('시설 소장 확인' in nav and await page.inner_text('#s9 h2') == '시설 소장 확인', '9번 이름: 시설 소장 확인')
        check((await page.inner_text('#s9 .chiefbox')).strip() == '', '9번 칸은 체크박스만 (글자 없음)')
        tops = await ev("['#f-elecKw','[data-group=powerPhase]','#f-mainBreakerA'].map(s => Math.round(document.querySelector(s).getBoundingClientRect().top))")
        check(len(set(tops)) == 1, f'전기용량·전원 방식·메인차단기 한 줄 (1280) {tops}')
        opts = await page.locator('[data-group=powerPhase] button').all_inner_texts()
        check(opts == ['단상 220V', '삼상 380V', '화재예방단자함'], '전원 방식 셋 중 하나: ' + ', '.join(opts))
        wrapped = await ev("[...document.querySelectorAll('[data-group=powerPhase] button')].some(b => b.scrollWidth > b.clientWidth + 1 || b.getBoundingClientRect().height > 50)")
        check(not wrapped, '버튼 글자 한 줄')
        await page.fill('#f-elecKw', '20'); await page.fill('#f-mainBreakerA', '100')
        await page.click('[data-choice=powerPhase][data-value=화재예방단자함]')
        check('판정은 하지 않습니다' in await page.inner_text('#brkStatus'), '화재예방단자함 → 메인차단기 판정 안 함 안내')
        await page.click('[data-choice=powerPhase][data-value="삼상 380V"]')
        s4 = await page.inner_text('#s4')
        check('설비 교체' in s4 and '디퓨져' in s4 and '유도등' not in s4 and '이설' not in s4 and await page.locator('#f-sprAdd').count() == 0, '소방·방염: 설비 교체 (스프링클러·감지기·디퓨져), 유도등·수량 칸 없음')
        await page.click('[data-choice=storeType][data-value=VP]')
        check(await page.locator('#s4 .seg.na').count() == 3, 'VP → 설비 교체 3항목 해당없음')
        await page.click('[data-choice=storeType][data-value=본매장]')
        await page.click('[data-choice=kitchen][data-value=없음]')
        await page.fill('#f-tenant', '샤넬 뷰티'); await page.fill('#f-location', 'B1F')
        await page.click('[data-act=finalize]')
        await page.wait_for_selector('.misslist')
        miss = await page.locator('.misslist [data-jump]').evaluate_all('l => l.map(b => b.dataset.jump)')
        check(not any(k.startswith('owner') for k in miss), '빠진 항목에 발주처 없음')
        check(not any(k in miss for k in ['waterproof', 'waterTest', 'kitchenExt', 'exhaustCmh', 'gasGrade', 'gasAlarm']), '주방공사 없음 → 해당없음 칸은 빠진 항목에 없음')
        check('sprReplace' in miss, '새 항목(스프링클러 교체)은 확인')
        await page.click('#missBack')
        await page.set_viewport_size({'width': 1024, 'height': 768}); await page.wait_for_timeout(200)
        tops = await ev("['#f-elecKw','[data-group=powerPhase]','#f-mainBreakerA'].map(s => Math.round(document.querySelector(s).getBoundingClientRect().top))")
        wrapped = await ev("[...document.querySelectorAll('[data-group=powerPhase] button')].some(b => b.getBoundingClientRect().height > 50)")
        check(len(set(tops)) == 1 and not wrapped, f'1024 태블릿도 한 줄 {tops}')
        await page.set_viewport_size({'width': 1280, 'height': 900})

        print('서류 요청')
        await page.fill('#f-contractorCompany', '대한인테리어'); await page.fill('#f-contractorName', '김시공'); await page.fill('#f-contractorEmail', 'kim@daehan.co.kr')
        await page.fill('#f-contractorTel', '01012345678')
        for k, v in [('docInsurance', '미제출'), ('docCad', '미제출'), ('docFR', '제출'), ('docFRPlan', '미제출')]:
            await page.click(f'[data-choice={k}][data-value={v}]')
        check(await page.locator('[data-act=docReq]').count() == 1, '미제출 안내 아래 ✉ 미제출 서류 요청')
        await page.click('[data-act=docReq]'); await page.wait_for_selector('[data-dk=docCad]')
        check(await page.locator('[data-dk=docFR]').is_disabled() and 'docInsurance' not in await page.inner_html('.dialog'), '제출된 방염서류는 막힘, 영업배상 책임보험은 없음')
        check('에비뉴엘 시설팀' in await page.inner_text('.dialog .msig'), '미리보기에 서명')
        await page.fill('#drExtra', '11/5까지')
        await page.click('#drGo')
        await page.wait_for_function("(window.__mockMails||[]).some(m => m.kind === 'doc')")
        m = await ev("window.__mockMails.find(m => m.kind === 'doc')")
        check('설계도면(CAD)' in m['body'] and '방염계획도' in m['body'] and '영업배상' not in m['body'] and '11/5까지' in m['body'], '보낸 메일: 설계도면·방염계획도만 + 덧붙일 말')
        await page.wait_for_selector('.sendlog')
        check('서류 요청' in await page.inner_text('.sendlog'), '보낸 메일·발송 기록에 서류 요청')

        print('원격 서명')
        await page.click('[data-sreq=safety] [data-act=sigReq]'); await page.wait_for_selector('[data-sw=safety]')
        check(await page.locator('[data-se=safety]').count() == 1 and await page.locator('#srGo').is_disabled(), '안전관리팀 이메일 칸, 비어 있으면 보내기 막힘')
        await page.fill('[data-se=safety]', 'safety.park@lotte.net')
        await page.click('label.sfile:has([data-sw=resp])')
        check(await page.input_value('[data-se=resp]') == 'kim@daehan.co.kr', '공사 책임자 = 시공업체 이메일 자동')
        await page.screenshot(path=OUT / 'v18_sigreq.png')
        await page.click('#srGo')
        await page.wait_for_function("(window.__mockMails||[]).filter(m => m.kind === 'sig').length === 2", timeout=60000)
        await page.wait_for_selector('[data-sreq=safety] .sreq.wait')
        check('서명 요청 보냄' in await page.inner_text('[data-sreq=safety]') and '서명 요청 보냄' in await page.inner_text('[data-sreq=resp]'), '서명표: ⏳ 서명 요청 보냄')
        pdf = await ev('window.__mockPdf')
        check(pdf and pdf['bytes'] > 20000, f"검토서 PDF 만들어 올림 ({pdf['bytes'] if pdf else 0} 바이트)")
        sm = await ev("window.__mockMails.find(m => m.kind === 'sig' && m.who === 'safety')")
        check('서명은 휴대폰으로 진행 가능합니다' in sm['body'], '메일에 휴대폰 서명 안내')
        token = sm['token']
        # 서명 페이지 (휴대폰)
        sp = await ctx.new_page(); sp.on('pageerror', lambda e: errors.append('sign pageerror: ' + str(e)))
        await sp.set_viewport_size({'width': 390, 'height': 844})
        await sp.route('**/fonts.g*/**', lambda r: r.abort())
        await sp.goto(URL + '?sign=' + token)
        await sp.wait_for_selector('#spPad')
        txt = await sp.inner_text('.signpg')
        check('안전관리팀' in txt and '샤넬 뷰티' in txt and 'PIN' not in txt and await sp.locator('#pin').count() == 0, '서명 페이지: PIN 없이 그 칸만')
        check('미리 들어 있습니다' not in txt, '"미리 들어 있습니다" 문구 없음')
        await sp.click('#spSend')
        check('성명·연락처' in await sp.inner_text('#spErr'), '비어 있으면 보내기 막음')
        await sp.fill('#spName', '박안전'); await sp.fill('#spTel', '01022223333')
        check(await sp.input_value('#spTel') == '010-2222-3333', '연락처 하이픈')
        box = await sp.locator('#spPad').bounding_box()
        await sp.mouse.move(box['x'] + 30, box['y'] + 120); await sp.mouse.down()
        for i in range(12): await sp.mouse.move(box['x'] + 40 + i * 20, box['y'] + 60 + (i % 3) * 30)
        await sp.mouse.up()
        await sp.screenshot(path=OUT / 'v18_signpage.png')
        await sp.click('#spSend')
        await sp.wait_for_selector('.sp-done')
        check('서명이 전달되었습니다' in await sp.inner_text('.signpg'), '마우스로 서명 → 전달 완료')
        await sp.reload(); await sp.wait_for_selector('.signpg h1')
        check('열 수 없습니다' in await sp.inner_text('.signpg'), '한 번 쓴 링크는 다시 못 엶')
        await sp.close()
        # 열어 둔 화면에서 저장 → 원격 서명 들어옴
        await page.fill('#f-salesName', '이영업')
        await page.click('[data-act=save]')
        await page.wait_for_function("window.__DR.review.safetySig && window.__DR.review.safetyName === '박안전'")
        check(await page.input_value('#f-safetyName') == '박안전' and await page.locator('[data-key=safetySig] img').count() == 1, '열어 둔 검토서에 원격 서명·성명 반영')
        check(await page.locator('[data-sreq=safety] .sreq').count() == 0, '서명한 칸은 요청 버튼 없음')
        log = await page.inner_text('.sendlog')
        check('서명 완료' in log and '서명 요청' in log, '발송 기록: 서명 요청 · 서명 완료')

        print('PDF 자동 보관 · 2차 변경 요약')
        await ev("window.__mockPdf = null")
        await page.click('[data-act=finalize]')
        if await page.locator('#missGo').count():
            await page.click('#missGo')
        await page.wait_for_function("window.__mockPdf && window.__mockPdf.auto", timeout=60000)
        await page.wait_for_function("/PDF 보관/.test((document.querySelector('.sendlog')||{}).innerText||'')")
        check(True, '검토 완료 → PDF 자동 보관, 발송 기록에 PDF 보관')
        await page.click('[data-act=next]')
        if await page.locator('.dialog .main-act').count():
            await page.click('.dialog .main-act')
        await page.wait_for_function("window.__DR.round === 2")
        await page.click('[data-choice=powerPhase][data-value="단상 220V"]')
        await page.fill('#f-elecKw', '5')
        await page.click('[data-choice=docCad][data-value=제출]')
        await page.evaluate("document.querySelector('[data-act=print]').click()")
        await page.wait_for_selector('.page'); await page.wait_for_timeout(400)
        chg = await page.inner_text('.page >> nth=1')
        check('1차 대비 변경 사항' in chg and '전원 방식' in chg and '20 kW' in chg and '삼상 380V' in chg and '단상 220V' in chg and '설계도면' in chg, '출력 2쪽: 1차 대비 변경 (이전 → 새 값)')
        await page.locator('.page >> nth=1').screenshot(path=OUT / 'v18_print2.png')
        await page.click('[data-act=backEdit]'); await page.wait_for_selector('#notes')

        print('대시보드 할 일 · 업체 이력')
        call = "(n, ...a) => new Promise((ok, no) => google.script.run.withSuccessHandler(ok).withFailureHandler(no)[n](...a))"
        await ev("async () => { const call = " + call + "; const A={pin:'1234',role:'소장'}; await call('apiSaveReview', A, {tenant:'에르메스', contractorCompany:'대한인테리어', docFRPlan:'미제출'}, false); const b = await call('apiSaveReview', A, {tenant:'디올', contractorCompany:'한빛'}, false); await call('apiSetChiefOk', A, b.store.id, 1, true); window.__mockAddLog(b.store.id, {t:'defect', d:'업무지원 앱 하자점검에서 발송 (2건)'}); }")
        await page.click('[data-act=dash]'); await page.wait_for_selector('[data-act=new]')
        await page.click('[data-act=refresh]'); await page.wait_for_timeout(500)
        todos = await page.inner_text('#todos')
        check('시설 소장 확인 대기' in todos and '시방서 미발송' in todos and '서류 미제출' in todos, '할 일: 시설 소장 확인 대기 · 시방서 미발송 · 서류 미제출')
        await page.click('.todo[data-k=chief]')
        names = await page.locator('.tbl .store-link').all_inner_texts()
        check('디올' not in names and len(names) == 2 and await page.locator('.filterchip').count() == 1, '누르면 시설 소장 확인 대기 매장만: ' + ', '.join(names))
        await page.click('.filterchip button')
        check(await page.locator('.tbl .store-link').count() == 3, '✕로 걸러 보기 끄기')
        body = await page.inner_text('#dashBody')
        check('하자 발송 ✓' in body and '서류 미제출 1' in body, '매장 이름 아래 하자 발송 ✓ · 서류 미제출 표시')
        check(await ev("[...document.querySelectorAll('.cf.chief')].every(e => e.innerText.trim() === '시설 소장 확인')"), '대시보드 버튼 글자: 시설 소장 확인')
        w = await ev("(() => { const r = document.querySelector('.tbl tbody tr'); return [r.querySelector('.cf[data-act=confirm]').getBoundingClientRect().width, r.querySelector('.cf.chief').getBoundingClientRect().width]; })()")
        check(abs(w[0] - w[1]) < 1, f'컨펌완료·시설 소장 확인 같은 폭 {w}')
        check(await ev("document.documentElement.scrollWidth <= innerWidth"), 'PC 표 넘침 없음')
        await page.screenshot(path=OUT / 'v18_dash.png')
        await page.click('.vlink >> text=대한인테리어')
        await page.wait_for_selector('.vend')
        vt = await page.inner_text('.vend')
        check('맡은 매장' in vt and '샤넬 뷰티' in vt and '에르메스' in vt and '디올' not in vt, '업체 이력: 그 업체 매장만')
        await page.locator('.vend').screenshot(path=OUT / 'v18_vendor.png')
        await page.click('.vend [data-vopen] >> nth=0'); await page.wait_for_selector('#notes')
        check(True, '이력에서 매장 누르면 검토서 열림')
        await page.click('[data-act=dash]'); await page.wait_for_selector('[data-act=new]')
        await page.click('[data-act=logout]')
        await page.fill('#pin', '5678'); await page.click('#loginForm button[type=submit]'); await page.wait_for_selector('[data-act=new]')
        check(await page.locator('.todo[data-k=chief]').count() == 0 and await page.locator('.todo').count() == 3, '부소장에게는 시설 소장 확인 대기 안 보임')

        print('휴대폰')
        await page.set_viewport_size({'width': 375, 'height': 800}); await page.reload(); await page.wait_for_selector('[data-act=new]')
        check(await ev('document.documentElement.scrollWidth') <= 375, '대시보드 넘침 없음')
        await b.close()
    print('ERRORS:', errors if errors else 'none')
    if errors:
        raise SystemExit(1)


srv = subprocess.Popen([sys.executable, '-m', 'http.server', str(PORT), '--bind', '127.0.0.1'], cwd=ROOT,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
try:
    time.sleep(1)
    asyncio.run(main())
finally:
    srv.terminate()
